function writeSheet(sheet, title, note, headers, rows, tableName, titleColor) {
  const lastCol = "G";
  const endRow = rows.length + 3;
  sheet.showGridLines = false;
  sheet.getRange(`A1:${lastCol}1`).merge();
  sheet.getRange("A1").values = [[title]];
  sheet.getRange(`A2:${lastCol}2`).merge();
  sheet.getRange("A2").values = [[note]];
  sheet.getRange("A3:G3").values = [headers];
  sheet.getRange(`A4:G${endRow}`).values = rows;
  sheet.getRange("A1:G1").format = { fill: titleColor, font: { bold: true, color: "#FFFFFF", size: 16 }, horizontalAlignment: "left", verticalAlignment: "center" };
  sheet.getRange("A2:G2").format = { fill: "#F3F6FA", font: { color: "#425466", italic: true, size: 10 }, wrapText: true, verticalAlignment: "center" };
  sheet.getRange("A3:G3").format = { fill: "#1F4E78", font: { bold: true, color: "#FFFFFF" }, horizontalAlignment: "center", verticalAlignment: "center", wrapText: true };
  sheet.getRange(`A4:G${endRow}`).format = { verticalAlignment: "center", wrapText: true };
  sheet.getRange(`A4:A${endRow}`).format.horizontalAlignment = "center";
  sheet.getRange(`C4:E${endRow}`).format.horizontalAlignment = "center";
  sheet.getRange(`A3:G${endRow}`).format.borders = { preset: "all", style: "thin", color: "#D9E2F3" };
  sheet.getRange("A1:G1").format.rowHeight = 28;
  sheet.getRange("A2:G2").format.rowHeight = 34;
  sheet.getRange("A3:G3").format.rowHeight = 30;
  sheet.getRange(`A4:G${endRow}`).format.rowHeight = 24;
  [7, 28, 13, 13, 23, 48, 55].forEach((width, idx) => sheet.getRangeByIndexes(0, idx, endRow, 1).format.columnWidth = width);
  sheet.freezePanes.freezeRows(3);
  const table = sheet.tables.add(`A3:G${endRow}`, true, tableName);
  table.style = "TableStyleMedium2";
  sheet.getRange("A3:G3").format = { fill: "#1F4E78", font: { bold: true, color: "#FFFFFF" }, horizontalAlignment: "center", verticalAlignment: "center", wrapText: true };
  sheet.getRange("A3:G3").format.rowHeight = 30;
}

