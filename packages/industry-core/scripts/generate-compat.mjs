import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const packageRoot=fileURLToPath(new URL('..',import.meta.url));
const repositoryRoot=path.resolve(packageRoot,'../..');
const read=relative=>readFileSync(path.join(packageRoot,relative),'utf8');

// Compatibility artifacts are local and self-contained, including file:// use.
// Only this generator writes derived copies; applications import the canonical modules.
export function generateCompatibility({root=repositoryRoot,check=false}={}) {
  const dataset=JSON.parse(read('data/industry-catalog.json'));
  const serialized=JSON.stringify(dataset);
  const match=read('matching.mjs').replace('export const matchMajorJobs','const matchMajorJobs');
  const selection=read('selection.mjs').replace(/^import .*\n/,'').replace('export const IndustryMajorSelection','const IndustryMajorSelection');
  const files=new Map([
    ['major-construction-platform/src/data/major-job-matching.js',`// Generated by packages/industry-core/scripts/generate-compat.mjs. Do not edit.\n;(function(root) {\n${match}\nroot.MAJOR_JOB_MATCHING = {match:matchMajorJobs};\n})(globalThis);\n`],
    ['major-construction-platform/src/data/industry-major-selection.js',`// Generated by packages/industry-core/scripts/generate-compat.mjs. Do not edit.\n;(function(root) {\nconst matchMajorJobs = major => root.MAJOR_JOB_MATCHING.match(major);\n${selection}\nroot.IndustryMajorSelection = IndustryMajorSelection;\n})(globalThis);\n`],
    ['major-construction-platform/src/data/industry-major-chain-data.ts',`import type { IndustryMajorChainDataset } from '../app/industry-major-chain-types'\n\nexport const INDUSTRY_MAJOR_CHAIN_DATA = JSON.parse(${JSON.stringify(serialized)}) as IndustryMajorChainDataset\n`],
    ['major-construction-platform/industry-major-chain-data.js',`globalThis.INDUSTRY_MAJOR_CHAIN_DATA = ${serialized};\n`],
    ['major-construction-platform/outputs/industry-major-chain-data.js',`globalThis.INDUSTRY_MAJOR_CHAIN_DATA = ${serialized};\n`],
    ['ai-course/src/generation/official-majors.json',read('data/official-majors.json')],
    ['ai-course/src/cms/chain-catalog.json',JSON.stringify({source:'major-construction-platform/src/data/industry-major-chain-data.ts',snapshot:'2026-09-08',chains:dataset.chains,relations:dataset.relations})],
  ]);
  const drift=[];
  for(const [relative,content] of files) {
    const file=path.join(root,relative);
    let current;try{current=readFileSync(file,'utf8');}catch{}
    // The ignored export directory is optional in a fresh clone.
    if(check && current === undefined && relative.startsWith('major-construction-platform/outputs/')) continue;
    if(current===content)continue;
    if(check){drift.push(relative);continue;}
    mkdirSync(path.dirname(file),{recursive:true});
    writeFileSync(file,content);
  }
  if(drift.length) throw new Error(`Shared industry artifacts differ; run node packages/industry-core/scripts/generate-compat.mjs:\n${drift.join('\n')}`);
  return [...files.keys()];
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  generateCompatibility({check:process.argv.includes('--check')});
}
