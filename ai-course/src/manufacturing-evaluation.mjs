export function addManufacturingEvaluation(project,key){
 if(!goals[key]||project.stages.length!==6||project.stages.some(s=>!s.tasks?.length))return project;
 project.stages.forEach((stage,i)=>{
  const [knowledge,skill,quality]=goals[key][i];
  const stageGoals=Object.fromEntries(Object.entries({knowledge,skill,quality:[quality]}).map(([category,titles])=>[category,titles.map((title,j)=>({id:`${stage.id}-evaluation-${category}-${j}`,title}))]));
  const allIds=Object.values(stageGoals).flat().map(g=>g.id);
  const weights=stage.tasks.length===taskWeights[i].length?taskWeights[i]:stage.tasks.map((_,j)=>j===stage.tasks.length-1?stageWeights[i]-Math.floor(stageWeights[i]/stage.tasks.length)*(stage.tasks.length-1):Math.floor(stageWeights[i]/stage.tasks.length));
  const scored=stage.tasks.map((task,j)=>{
   const example=task.id===`${project.id}-stage-${i}-task-${j}`?activities[key][i][j]:null;
   const goalIds=j>=2?allIds:j===0?[stageGoals.knowledge[0].id,stageGoals.knowledge[1].id,stageGoals.skill[0].id,stageGoals.quality[0].id]:[stageGoals.knowledge[1].id,stageGoals.skill[1].id,stageGoals.quality[0].id];
   return {id:`${stage.id}-evaluation-activity-${j}`,title:example?.[0]||`任务成果检查：${task.title}`,taskId:task.id,goalIds,evidence:`${task.learningActivity?.evidence||task.title+'任务成果'}；附任务编号、程序/文档版本、操作者及复核记录。`,criteria:example?.[1]||`${task.learningActivity?.criteria||'输入、操作和成果与任务说明一致，异常保留原始数据，整改与复测分别记录。'} 核验步骤：${task.learningActivity?.steps||'对照本任务说明逐项核验，并由教师确认完成条件。'}`,weight:weights[j],scored:true,subjects:j===0?['teacher','self']:['teacher','peer']};
  });
  const feedback=formative[key].find(([index])=>index===i);
  stage.evaluation={source,goals:stageGoals,activities:[...scored,...(feedback?[{id:`${stage.id}-evaluation-feedback`,title:feedback[1],taskId:stage.tasks[0].id,goalIds:[stageGoals.knowledge[0].id,stageGoals.quality[0].id],evidence:'个人诊断/反思单、小组轮岗日志与教师反馈记录；保留原始问题及后续改进。',criteria:feedback[2],weight:0,scored:false,subjects:i===3?['teacher','self','agent']:['teacher','self','peer']}]:[])]};
 });
 return project;
}
export function migrateManufacturingEvaluation(storage,projects,raw){
 if(storage.getItem(EVALUATION_DEMO_REVISION)==='done')return projects;
 const eligible=projects.filter(p=>['plc-demo-conveyor','plc-demo-sorting','plc-demo-assembly'].includes(p.id)&&p.stages.length===6&&p.stages.every(s=>!Object.hasOwn(s,'evaluation')&&s.tasks?.length));
 if(eligible.length){
  if(raw!==null&&!storage.getItem(EVALUATION_BACKUP_KEY))storage.setItem(EVALUATION_BACKUP_KEY,raw);
  eligible.forEach(p=>addManufacturingEvaluation(p,p.id.slice('plc-demo-'.length)));
  storage.setItem('ai-course-projects-v1',JSON.stringify(projects));
 }
 storage.setItem(EVALUATION_DEMO_REVISION,'done');
 return projects;
}
