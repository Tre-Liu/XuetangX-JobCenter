def f(size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONT, size=size)


def wrap(text: str, width: int = 30) -> list[str]:
    lines: list[str] = []
    for part in text.split("\n"):
        lines.extend(textwrap.wrap(part, width=width, break_long_words=False) or [""])
    return lines


def badge(draw: ImageDraw.ImageDraw, xy: tuple[int, int], number: int) -> None:
    x, y = xy
    r = 13
    draw.ellipse((x - r, y - r, x + r, y + r), fill=RED)
    draw.text((x, y - 1), str(number), font=f(15), fill=(255, 255, 255, 255), anchor="mm")


def legend(draw: ImageDraw.ImageDraw, x: int, y: int, title: str, entries: list[dict]) -> None:
    panel_w = 1120
    panel_h = 1320
    draw.rounded_rectangle((x, y, x + panel_w, y + panel_h), radius=18, fill=PANEL, outline=LINE, width=2)
    draw.text((x + 24, y + 24), title, font=f(26), fill=INK)
    draw.text((x + 24, y + 62), "底图来自当前 demo 实时截图；红色编号贴在页面真实字段位置。", font=f(16), fill=MUTED)

    columns = 2
    per_col = (len(entries) + columns - 1) // columns
    col_w = (panel_w - 54) // columns
    for col in range(columns):
        xx = x + 24 + col * col_w
        yy = y + 102
        for item in entries[col * per_col:(col + 1) * per_col]:
            draw.ellipse((xx, yy + 4, xx + 24, yy + 28), fill=RED)
            draw.text((xx + 12, yy + 16), str(item["n"]), font=f(13), fill=(255, 255, 255, 255), anchor="mm")
            draw.text((xx + 34, yy), item["field"], font=f(16), fill=INK)
            yy += 23
            for line in wrap(item["db"], width=30)[:3]:
                draw.text((xx + 34, yy), line, font=f(13), fill=MUTED)
                yy += 17
            yy += 6
            draw.line((xx, yy, xx + col_w - 18, yy), fill=LINE, width=1)
            yy += 8


def render(source_name: str, output_name: str, title: str, entries: list[dict]) -> None:
    image = Image.open(SRC / source_name).convert("RGBA")
    canvas = Image.new("RGBA", (image.width + 1170, max(image.height, 1400)), (246, 249, 255, 255))
    canvas.paste(image, (0, 0))
    draw = ImageDraw.Draw(canvas)
    for item in entries:
        badge(draw, item["xy"], item["n"])
    legend(draw, image.width + 24, 30, title, entries)
    canvas.convert("RGB").save(OUT / output_name, quality=95)


