// Rebuild from the audited extraction, without inferring sources from similar task names.
import { readFile, writeFile, access } from 'node:fs/promises'
const input = new URL('../../.tmp/typical-task-extraction/data/detail.json', import.meta.url)
const rows = JSON.parse(await readFile(input, 'utf8'))
const index = {}
const checkedPaths = new Set()
for (const row of rows) {
  if (!row['参考人培文件'] || !row['来源路径']) continue
  if (!checkedPaths.has(row['来源路径'])) {
    await access(row['来源路径'])
    checkedPaths.add(row['来源路径'])
  }
  const source = {
    taskId: row['任务ID'], file: row['参考人培文件'], school: row['学校'],
    major: row['专业'], locator: row['来源定位'], sha256: row['SHA-256']
  }
  for (const job of new Set([row['岗位'], row['来源岗位']].filter(Boolean))) {
    const key = JSON.stringify([job, row['典型工作任务']])
    const items = index[key] ??= []
    if (!items.some((item) => item.sha256 === source.sha256 && item.locator === source.locator)) items.push(source)
  }
}
const output = new URL('../src/data/portrait-task-sources.js', import.meta.url)
await writeFile(output, '// Generated by scripts/generate-portrait-task-sources.mjs from audited task records.\n;(typeof window === "undefined" ? globalThis : window).PortraitTaskSourceIndex = ' + JSON.stringify(index, null, 2) + '\n')
console.log(`Exported ${Object.keys(index).length} job/task keys from ${new Set(rows.map((row) => row['任务ID'])).size} tasks; verified ${checkedPaths.size} source paths.`)
