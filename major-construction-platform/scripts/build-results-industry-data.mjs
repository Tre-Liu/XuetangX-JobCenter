import { writeFile } from 'node:fs/promises'
import { INDUSTRY_CHAINS, INDUSTRY_NODES, INDUSTRY_CHAIN_RELATIONS, JOB_INDUSTRY_RELATIONS, JOB_CARDS, COURSE_NODES, getJobDetail } from '../src/mock/job-center.ts'
import { industrySankeyStages, industrySankeyNodes, industrySankeyLinks, industryCompanyItems } from '../src/app/talent-industry-data.ts'
import { industryDetails } from './results-industry-detail-data.mjs'

// One offline archive for both results entries. Regenerate after changing job-center.ts.
const abilityCatalog = []
const indexes = new Map()
const chainDescriptions = {
  'chain-foundation':'围绕工程数据、智能测绘、建筑物联网和装配式构件，涵盖数据资源、感知装备及部品供给，支撑智能建造的基础能力建设。',
  'chain-platform':'围绕BIM协同设计、智慧工地和建筑机器人应用，连接工程数据、数字平台与专业服务，支撑工程设计、建造实施与项目协同。',
  'chain-application':'围绕智能检测、绿色建造、智慧运维与装配式建造，覆盖施工现场管理、质量安全监管和建筑运营等应用场景。'
}
const jobs = JOB_CARDS.map(job => {
  const detail = getJobDetail(job.id)
  const abilityIndexes = detail.abilities.map(a => {
    const key = JSON.stringify(a)
    if (!indexes.has(key)) { indexes.set(key, abilityCatalog.length); abilityCatalog.push(a) }
    return indexes.get(key)
  })
  return { id:job.id, name:job.name, industryNodeId:job.industryNodeId, abilityIndexes,
    jdText:[detail.workSummary, detail.requirements].filter(Boolean).join('\n'),
    jdBasis:'岗位画像配置中的工作概述与任职要求；测算待核验，非已核验招聘记录。',
    tasks:detail.tasks.map(t => ({name:t.name, description:t.description, abilities:t.abilities})),
    courses:COURSE_NODES.filter(c => c.jobIds.includes(job.id)).map(c => c.name) }
})
const jobNodeMap = {
  'node-bim-data':['software'], 'node-smart-survey':['survey'], 'node-iot-sensing':['equipment'],
  'node-prefab':['materials','prefab'], 'node-bim-platform':['design','bim-service'],
  'node-smart-site':['smart-site','epc','regulation'], 'node-robotics':['robotics','construction'],
  'node-monitoring':['testing'], 'node-green-ops':['green-ops','renewal']
}
const detailCompanies = [], detailLinks = []
const stageOrder = { upstream:0, midstream:1, downstream:2 }
for (const detail of industryDetails) {
  jobNodeMap[detail.industryId].push(detail.id)
  const parent = industrySankeyNodes.find(n => n.id === detail.parent)
  detailCompanies.push(...industryCompanyItems.filter(c => c.industry === parent.name).map(({name,products}) => ({name,products,industry:detail.name})))
  if (stageOrder[parent.stage] !== stageOrder[detail.stage]) {
    const forward = stageOrder[parent.stage] < stageOrder[detail.stage]
    detailLinks.push({source:forward ? parent.id : detail.id,target:forward ? detail.id : parent.id,value:1})
  }
}
// Connect the processing and delivery subdivisions within each parent domain.
for (const first of industryDetails.filter(n => n.stage === 'midstream')) {
  const last = industryDetails.find(n => n.industryId === first.industryId && n.stage === 'downstream')
  if (last) detailLinks.push({source:first.id,target:last.id,value:1})
}
const archive = { basis:'现有智能建造专业配置与岗位画像测算；细分环节及沿用的企业、岗位关联待核验；非实时招聘统计。',
  chains:INDUSTRY_CHAINS.map(chain=>({...chain,description:chainDescriptions[chain.id]||''})), industries:INDUSTRY_NODES, chainRelations:INDUSTRY_CHAIN_RELATIONS,
  jobRelations:JOB_INDUSTRY_RELATIONS, abilityCatalog, jobs,
  industryOverview: {
    stages:industrySankeyStages.map(({key,label,summary})=>({key,label,summary})),
    nodes:[...industrySankeyNodes.map(({id,stage,name,techFields})=>({id,stage,name,techFields})),
      ...industryDetails.map(({id,stage,name,techFields,parent})=>({id,stage,name,techFields,parentId:parent,basis:'按既有产业配置细分，关联沿用父级档案，待核验。'}))],
    links:[...industrySankeyLinks.map(({source,target,value})=>({source,target,value})),...detailLinks],
    companies:[...industryCompanyItems.map(({name,industry,products})=>({name,industry,products})),...detailCompanies],
    jobNodeMap
  } }
await writeFile(new URL('../src/results-home/industry-data.js', import.meta.url),
  '// Generated by scripts/build-results-industry-data.mjs from src/mock/job-center.ts.\n;globalThis.ResultsIndustryData = '+JSON.stringify(archive)+'\n')
console.log(`产教模型档案：${jobs.length} 个岗位，${abilityCatalog.length} 条去重能力定义`)
