  function withPracticePoints(graph) {
    if (!graph || graph.curriculumRevision !== revision || graph.practicePointsAdded) return graph
    const courseIds = new Set(graph.courses.map(course => course.id))
    if (!practicePoints.every(([id]) => courseIds.has(id))) return graph

    // Append to existing branches so stored point paths and relation endpoints stay valid.
    const updated = JSON.parse(JSON.stringify(graph))
    for (const [id, sectionName, names] of practicePoints) {
      const course = updated.courses.find(item => item.id === id)
      const owners = course.topics.flatMap(topic => [...(topic.sections || []), ...(topic.points ? [topic] : [])])
      const owner = owners.find(item => item.name === sectionName)
      if (!owner) continue
      const existing = new Set(owners.flatMap(item => item.points))
      for (const name of names) {
        if (existing.has(name)) continue
        const index = owner.points.push(name) - 1
        const domains = owner.pointDomains ||= {}
        const notes = owner.pointNotes ||= {}
        domains[index] = []
        notes[index] = {description: '课程实训补充建议，待教学审核。'}
      }
    }
    updated.practicePointsAdded = true
    return updated
  }

